-- Reference schema. Actual schema is applied at runtime by lib/schema.ts.
-- Keep these definitions in sync.

CREATE TABLE IF NOT EXISTS EXPENSE_GROUP (
  ID          TEXT NOT NULL PRIMARY KEY,
  CREATED_AT  TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT  TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DELETED_AT  TEXT,
  NAME        TEXT NOT NULL,
  EMOJI       TEXT,
  COLOR       TEXT NOT NULL DEFAULT 'blue',
  SORT_ORDER  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS EXPENSE (
  ID           TEXT NOT NULL PRIMARY KEY,
  CREATED_AT   TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT   TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DELETED_AT   TEXT,
  CATEGORY     TEXT NOT NULL DEFAULT 'other',
  GROUP_ID     TEXT,
  NAME         TEXT NOT NULL,
  AMOUNT       REAL NOT NULL,
  MONTH        TEXT NOT NULL,
  NOTES        TEXT,
  IS_RECURRING INTEGER NOT NULL DEFAULT 0,
  TAGS         TEXT
);

CREATE INDEX IF NOT EXISTS IDX_EXPENSE_MONTH      ON EXPENSE(MONTH);
CREATE INDEX IF NOT EXISTS IDX_EXPENSE_DELETED_AT ON EXPENSE(DELETED_AT);
CREATE INDEX IF NOT EXISTS IDX_EXPENSE_GROUP      ON EXPENSE(GROUP_ID);

CREATE TABLE IF NOT EXISTS IMPORT_PATTERN (
  ID          TEXT NOT NULL PRIMARY KEY,
  CREATED_AT  TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PATTERN     TEXT NOT NULL,
  CATEGORY    TEXT NOT NULL,
  GROUP_ID    TEXT,
  PRIORITY    INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS IDX_IMPORT_PATTERN_PRIORITY ON IMPORT_PATTERN(PRIORITY DESC);

CREATE TABLE IF NOT EXISTS APP_SETTING (
  NAME       TEXT NOT NULL PRIMARY KEY,
  VALUE      TEXT NOT NULL,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BUDGET (
  CATEGORY   TEXT NOT NULL PRIMARY KEY,
  AMOUNT     REAL NOT NULL,
  UPDATED_AT TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
